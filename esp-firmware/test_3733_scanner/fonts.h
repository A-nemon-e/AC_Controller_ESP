// ===== 辅助函数：绘制字符 =====

// 绘制6×10数字到framebuffer
void drawChar6x10(uint8_t framebuffer[42][11], uint8_t x, uint8_t y,
                  uint8_t digit) {
  if (digit > 9)
    return;

  for (uint8_t row = 0; row < 10; row++) {
    uint8_t rowData = FONT_6X10_DIGITS[digit][row];
    for (uint8_t col = 0; col < 6; col++) {
      if (rowData & (1 << (7 - col))) {
        if (x + col < 42 && y + row < 11) {
          framebuffer[x + col][y + row] = 255;
        }
      }
    }
  }
}

// 绘制6×10冒号
void drawColon6x10(uint8_t framebuffer[42][11], uint8_t x, uint8_t y) {
  for (uint8_t row = 0; row < 10; row++) {
    uint8_t rowData = FONT_6X10_COLON[row];
    for (uint8_t col = 0; col < 6; col++) {
      if (rowData & (1 << (7 - col))) {
        if (x + col < 42 && y + row < 11) {
          framebuffer[x + col][y + row] = 255;
        }
      }
    }
  }
}

